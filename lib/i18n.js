const Ctx = createContext({ lang: "fr", t: D.fr, setLang: () => {} });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("fr");
  useEffect(() => {
    try { const s = localStorage.getItem("css_lang"); if (s && D[s]) setLangState(s); } catch (e) {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = D[lang].dir;
  }, [lang]);
  function setLang(l) { setLangState(l); try { localStorage.setItem("css_lang", l); } catch (e) {} }
  return <Ctx.Provider value={{ lang, t: D[lang], setLang }}>{children}</Ctx.Provider>;
}
export const useLang = () => useContext(Ctx);
